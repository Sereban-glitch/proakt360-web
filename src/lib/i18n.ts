export const dictionaries: Record<Lang, Dict> = { ru, uk };
export type TKey = keyof typeof ru;

type LangStore = {
  lang: Lang;
  setLang: (lang: Lang) => void;
};

export const useLangStore = create<LangStore>()(
  persist(
    (set) => ({
      lang: "ru",
      setLang: (lang) => set({ lang }),
    }),
    { name: "proakt360-lang" }
  )
);

export function useI18n() {
  const lang = useLangStore((s) => s.lang);
  const setLang = useLangStore((s) => s.setLang);
  const t = (key: TKey): string => dictionaries[lang][key] ?? key;
  return { lang, setLang, t };
}

/** Словарь для произвольного языка (кабинет клиента: локаль объекта). */
export function dictFor(lang: Lang): Dict {
  return dictionaries[lang] ?? dictionaries.ru;
}
